"""Checks for the partner SOW tool. Loads the page headless, exercises each template and prints ✅/❌ lines.

    python3 check.py index.html [screenshot_dir]
"""
import asyncio
import json
import os
import re
import sys

from playwright.async_api import async_playwright

PATH = os.path.abspath(sys.argv[1])
SHOTS = sys.argv[2] if len(sys.argv) > 2 else None
EXPECTED_ORDER = ['cja', 'commerce', 'aem', 'fsi', 'abv', 'coworker']
EXPECTED_ONE_TIME_HOURS = {'cja': 216, 'commerce': 216, 'aem': 1792, 'fsi': 808, 'abv': 152, 'coworker': 156}
EXPECTED_MONTHLY_HOURS = {'cja': 104, 'commerce': 104, 'aem': 120, 'fsi': 104, 'abv': 104, 'coworker': 32}
EXPECTED_STARTERS = {'cja': ['L01', 'L02', 'C01', 'C06', 'O01', 'O02'], 'commerce': ['L01', 'L02', 'L03', 'C02', 'O01', 'O02'], 'aem': ['L01', 'L02', 'A04', 'A01', 'A02', 'A03', 'A05', 'SO1', 'C03', 'O01', 'SO2', 'O02'], 'fsi': ['L01', 'L02', 'F02', 'C04', 'O01', 'O02'], 'abv': ['L01', 'L02', 'C05', 'O01', 'O02'], 'coworker': ['CW01', 'CW02', 'CW03', 'CW07', 'CW05', 'CW06']}
EXPECTED_OPTIONAL = {'cja': 5, 'commerce': 6, 'aem': 5, 'fsi': 6, 'abv': 5, 'coworker': 2}

results = []


def check(name, ok, detail=''):
    results.append(ok)
    print(('✅ ' if ok else '❌ ') + name + (': ' + detail if detail else ''))


async def main():
    html = open(PATH, encoding='utf-8').read()
    stage = {x['id']: x['stage'] for x in json.loads(re.search(r'<script>const CATALOG=(\[.*?\]);</script>', html, re.S).group(1))}
    check('no em or en dashes in the file', '—' not in html and '–' not in html)
    check('no Adobe Consulting Services mention', 'consulting services' not in html.lower())
    check('no software pricing in the file', not re.search(r'\$\s?\d', html) and 'RATE_RANGE=[100,300]' in html)
    check('no navy template colors left', not any(c in html.lower() for c in ('#1c2e3e', '#203343', '#e16a5c', '#e35242', '#647482')))
    check('no planning note or repeated disclaimers (step 7: one intro line instead)', 'planning-note' not in html and 'estimateNote' not in html and 'library-note' not in html)
    check('every product-based service carries a source and a title (39 of 40; executive alignment has none)', html.count('"sourceTitle": "') == 39 and html.count('"source": "http') == 39)
    check('CDN log forwarding in setup, the CJA connection and the SOW document', html.count('CDN log forwarding') >= 3 and 'Dependencies and risks' in html)
    check('Impact Measurement Engine in the pilot and the monthly review', html.count('Impact Measurement Engine') >= 3)
    check('paid offer and org-enabled CJA on the connection line', 'paid Brand Visibility offer' in html and 'enabled for the organization' in html)
    check('no dead scopeText fields in the catalog', '"scopeText"' not in html)
    check('200 prompts to start, nowhere 50', '200 prompts to start' in html and 'up to 50 prompts' not in html)
    check('AEM play reads as a new-site pursuit', 'Build the site on AEM Sites with Edge Delivery Services' in html)
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        page = await browser.new_page(viewport={'width': 1440, 'height': 1000})
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('console', lambda m: errors.append(m.type + ': ' + m.text) if m.type == 'error' else None)
        await page.goto('file://' + PATH)
        await page.wait_for_timeout(1200)
        check('page loads with no console or script errors', not errors, '; '.join(errors)[:300])
        check('Adobe logo in the masthead', await page.locator('.masthead img[alt="Adobe"]').count() == 1)
        font = await page.evaluate("getComputedStyle(document.body).fontFamily")
        check('body font is Source Sans 3', 'Source Sans 3' in font, font)
        order = await page.evaluate('Object.keys(PLAYS)')
        check('six templates in deck order, then Your own play (built on the canvas)', order == EXPECTED_ORDER + ['custom'], ','.join(order))
        check('no left-hand play list: the play comes from the Build canvas, with a Build tab and Change play to go back', await page.locator('#plays, .sidebar').count() == 0 and await page.locator('.steps [data-build]').count() == 1 and await page.locator('.topbar [data-build]').count() == 1)
        title = await page.text_content('#play-title')
        check('CJA play opens first', title == 'Brand Visibility + Customer Journey Analytics', title)
        for play in EXPECTED_ORDER:
            await page.evaluate("p=>{state.play=p;go('scope');}", play)
            await page.click('[data-step="services"]')
            await page.fill('#service-rate', '150')
            await page.wait_for_timeout(120)
            one = await page.text_content('.total-card:nth-child(1) small')
            month = await page.text_content('.total-card:nth-child(2) small')
            one_h = int(one.split()[0].replace(',', ''))
            month_h = int(month.split()[0].replace(',', ''))
            check(f'{play}: starter hours one-time {one_h}, monthly {month_h}', one_h == EXPECTED_ONE_TIME_HOURS[play] and month_h == EXPECTED_MONTHLY_HOURS[play])
            ids = await page.eval_on_selector_all('.service-card', 'els=>els.map(e=>e.dataset.line)')
            grouped = [i for st in ('Launch', 'Connect', 'Optimize') for i in EXPECTED_STARTERS[play] if stage[i] == st]
            check(f'{play}: starting services in order, grouped Launch, Connect, Optimize', ids == grouped, ','.join(ids))
            heads = await page.eval_on_selector_all('.stage-head h3', 'els=>els.map(e=>e.textContent)')
            check(f'{play}: each stage heading shows once', len(heads) == len(set(heads)), ','.join(heads))
            optional = await page.locator('#service-extensions button[data-add]').count()
            check(f'{play}: optional services offered', optional == EXPECTED_OPTIONAL[play], str(optional))
            cards = await page.locator('.service-card').count()
            sources = await page.eval_on_selector_all('.service-card .service-source a', 'els=>els.map(e=>e.href)')
            check(f'{play}: every service card shows a source link', cards == len(sources) and all(s.startswith('http') for s in sources), f'{cards} cards, {len(sources)} links')
            intro = await page.text_content('#services-panel .service-intro p')
            check(f'{play}: one intro line on the Services step', intro.startswith('Starting hours for the work in this play.'), intro[:60])
        await page.evaluate("p=>{state.play=p;go('scope');}", 'cja')
        await page.click('[data-step="services"]')
        await page.click('#add-service')
        await page.wait_for_timeout(200)
        lib = await page.locator('#available-services .available').count()
        lib_src = await page.locator('#available-services .available a').count()
        check('service library lists the unselected services with sources (executive alignment has none)', lib > 0 and lib == lib_src + 1, f'{lib} services, {lib_src} links')
        await page.keyboard.press('Escape')
        await page.click('[data-step="document"]')
        await page.wait_for_timeout(300)
        rule = await page.evaluate("getComputedStyle(document.querySelector('.sow-doc-header')).borderTopColor")
        check('SOW document top rule is black, no Adobe branding on the partner paper', rule == 'rgb(28, 28, 28)', rule)
        doc_logo = await page.locator('#sow-preview img').count()
        check('no logo inside the SOW document', doc_logo == 0)
        sections = await page.locator('#sow-preview .sow-section').count()
        check('SOW document renders its nine sections', sections == 9, str(sections))
        # ---- customer size switch
        catalog = {s['id']: s for s in json.loads(re.search(r'<script>const CATALOG=(\[.*?\]);</script>', html, re.S).group(1))}
        await page.evaluate("p=>{state.play=p;go('scope');}", 'aem')
        await page.click('[data-step="services"]')
        pressed = await page.get_attribute('#size-switch button[data-size="typical"]', 'aria-pressed')
        check('size switch shows Typical pressed by default', pressed == 'true')
        starters = EXPECTED_STARTERS['aem']
        for size, key in (('small', 'low'), ('large', 'high'), ('typical', 'base')):
            await page.click(f'#size-switch button[data-size="{size}"]')
            await page.wait_for_timeout(150)
            one = int((await page.text_content('.total-card:nth-child(1) small')).split()[0].replace(',', ''))
            month = int((await page.text_content('.total-card:nth-child(2) small')).split()[0].replace(',', ''))
            want_one = sum(catalog[i][key] for i in starters if catalog[i]['unit'] != 'monthly')
            want_month = sum(catalog[i][key] for i in starters if catalog[i]['unit'] == 'monthly')
            check(f'AEM at {size}: one-time {one}h, monthly {month}h', one == want_one and month == want_month, f'expected {want_one} and {want_month}')
        await page.evaluate("p=>{state.play=p;go('scope');}", 'cja')
        await page.click('[data-step="services"]')
        one = int((await page.text_content('.total-card:nth-child(1) small')).split()[0].replace(',', ''))
        check('size applies across templates (CJA still Typical after the AEM round trip)', one == EXPECTED_ONE_TIME_HOURS['cja'], str(one))
        await page.fill('[data-line="L01"] [data-line-field="hours"]', '100')
        await page.click('#size-switch button[data-size="small"]')
        await page.wait_for_timeout(150)
        kept = await page.input_value('[data-line="L01"] [data-line-field="hours"]')
        other = await page.input_value('[data-line="L02"] [data-line-field="hours"]')
        check('an edited line keeps its hours when the size changes', kept == '100' and int(other) == catalog['L02']['low'], f'{kept}, {other}')
        await page.click('[data-line="L01"] .scope-editor summary')
        await page.click('[data-line="L01"] [data-reset]')
        await page.wait_for_timeout(150)
        restored = await page.input_value('[data-line="L01"] [data-line-field="hours"]')
        check('restore follows the chosen size', int(restored) == catalog['L01']['low'], restored)
        await page.click('#add-service')
        await page.click('.custom-entry summary')
        await page.fill('#custom-name', 'Check custom')
        await page.fill('#custom-scope', 'A partner-defined line')
        await page.fill('#custom-hours', '25')
        await page.click('#custom-form button[type="submit"]')
        await page.wait_for_timeout(200)
        await page.click('#size-switch button[data-size="large"]')
        await page.wait_for_timeout(150)
        custom_hours = await page.eval_on_selector_all('.service-card', "els=>els.filter(e=>e.dataset.line.startsWith('CUSTOM')).map(e=>e.querySelector('[data-line-field=hours]').value)")
        check('custom services keep their hours at any size', custom_hours == ['25'], ','.join(custom_hours))
        saved = await page.evaluate("JSON.parse(localStorage.getItem('partner-sow-studio-v6')).size")
        check('the size is saved with the draft', saved == 'large', str(saved))
        await page.click('#size-switch button[data-size="typical"]')
        await page.wait_for_timeout(150)
        # ---- a dollar figure from the start (step 4) and the caption that explains it (step 5)
        fresh = await browser.new_page(viewport={'width': 1440, 'height': 1000})
        fresh.on('pageerror', lambda e: errors.append(str(e)))
        await fresh.goto('file://' + PATH)
        await fresh.wait_for_timeout(1000)
        await fresh.evaluate("p=>{state.play=p;go('scope');}", 'aem')
        await fresh.click('[data-step="services"]')
        await fresh.wait_for_timeout(150)
        # ---- step 7 (Adam, Oct 29 11:42 pm: mockup A): one strip, a heading over the totals, hours until a rate is entered
        strongs = await fresh.eval_on_selector_all('.total-card strong', 'els=>els.map(e=>e.textContent)')
        labels = await fresh.eval_on_selector_all('.total-card span', 'els=>els.map(e=>e.textContent)')
        check('totals: One-time implementation, Monthly recurring, Year one', labels == ['One-time implementation', 'Monthly recurring', 'Year one'], ' | '.join(labels))
        check('no rate yet: the cards show a dollar blank, never hours (AEM, Typical)', strongs == ['$ ___'] * 3 and 'hours' not in ' '.join(await fresh.eval_on_selector_all('.total-card', 'els=>els.map(e=>e.textContent)')), ' | '.join(strongs))
        body = await fresh.inner_text('#services-panel')
        check('no $100 to $300 ranges in the figures, only the note under the rate', body.count('$100 to $300') == 1 and ' to $' not in body.replace('$100 to $300', ''), str(body.count('$100 to $300')))
        hint = await fresh.text_content('#rate-hint')
        check('under the rate: Partner rates run about $100 to $300', hint == 'Partner rates run about $100 to $300', hint)
        head = await fresh.text_content('.earn-head h3'); cap = await fresh.text_content('#earn-caption')
        check('heading over the totals and what to do', head == 'What a partner makes on this play' and cap == 'Enter your rate to see your dollars.', head + ' / ' + cap)
        size = await fresh.evaluate("(()=>{const f=document.querySelector('.estimate-strip .size-field');return f?f.textContent:''})()")
        titles = await fresh.eval_on_selector_all('#size-switch button', 'els=>els.map(e=>e.title)')
        check('customer size sits in the strip, set from the Scope step, definitions on the buttons', 'Set from the prompts on the Scope step' in size and titles[0].startswith('Up to 200 prompts') and titles[2].startswith('1,000+ prompts'), size[:80])
        gone = await fresh.evaluate("!document.querySelector('.estimate-caption')&&!document.querySelector('.size-defs')&&!document.querySelector('.planning-note')")
        check('the old caption, size definitions paragraph and planning note are gone', gone)
        order = await fresh.evaluate("(()=>{const h=document.querySelector('.earn-head');return h.previousElementSibling.className+'>'+h.nextElementSibling.id})()")
        check('strip, then the heading, then the totals', order == 'estimate-strip>totals', order)
        heads = await fresh.eval_on_selector_all('#service-lines .stage-head h3', 'els=>els.map(e=>e.textContent)')
        tags = await fresh.eval_on_selector_all('#service-lines .stage-head .tag', 'els=>els.map(e=>e.textContent)')
        check('services grouped by stage with tags', heads == ['Launch', 'Connect', 'Optimize'] and tags == ['Fixed scope', 'Fixed scope', 'Program'], ','.join(heads) + ' / ' + ','.join(tags))
        first_fee = await fresh.text_content('[data-line="L01"] .line-fee strong')
        check('a line says At your rate until a rate is set', first_fee == 'At your rate', first_fee)
        placeholder = await fresh.get_attribute('#service-rate', 'placeholder')
        check('rate field placeholder reads Enter your rate', placeholder == 'Enter your rate', str(placeholder))
        await fresh.fill('#service-rate', '150')
        await fresh.wait_for_timeout(150)
        strongs = await fresh.eval_on_selector_all('.total-card strong', 'els=>els.map(e=>e.textContent)')
        smalls = await fresh.eval_on_selector_all('.total-card small', 'els=>els.map(e=>e.textContent)')
        check('rate entered: the hours become fees', strongs == ['$268,800', '$18,000 a month', '$484,800'], ' | '.join(strongs))
        check('rate entered: the hours move under the fees', smalls[0] == '1,792 hours' and smalls[1] == '120 hours a month, for 12 months', ' | '.join(smalls))
        first_fee = await fresh.text_content('[data-line="L01"] .line-fee strong')
        check('a line shows its fee once a rate is set', first_fee == '$9,600', first_fee)
        cap = await fresh.text_content('#earn-caption')
        check('the line under the heading names the entered rate', cap.startswith('At your rate of $150 an hour.'), cap)
        await fresh.fill('#service-months', '6')
        await fresh.wait_for_timeout(150)
        labels = await fresh.eval_on_selector_all('.total-card span', 'els=>els.map(e=>e.textContent)')
        check('the third total follows the months (6 months)', labels[2] == '6 months', labels[2])
        await fresh.fill('#service-months', '12')
        await fresh.fill('#service-rate', '')
        await fresh.fill('[data-line="A01"] [data-line-field="rate"]', '200')
        await fresh.wait_for_timeout(150)
        strongs = await fresh.eval_on_selector_all('.total-card strong', 'els=>els.map(e=>e.textContent)')
        check('one line priced, the rest open: the totals stay blank until every line has a rate', strongs[0] == '$ ___', strongs[0])
        await fresh.click('[data-step="document"]')
        await fresh.wait_for_timeout(300)
        note = await fresh.locator('#sow-preview .sow-review-note', has_text='Complete the missing hourly rates').count()
        check('SOW document still asks for the rates rather than printing a range', note == 1)
        risks = await fresh.locator('#sow-preview .sow-context', has_text='Dependencies and risks').count()
        check('SOW document carries the dependencies and risks block in the scope section', risks == 1)
        # ---- the Scope step's prompt count sets the size until the partner picks one
        await fresh.click('[data-step="scope"]')
        await fresh.fill('[data-cover="prompts"]', '1,500 prompts across 4 markets')
        await fresh.wait_for_timeout(200)
        auto = await fresh.evaluate("JSON.parse(localStorage.getItem('partner-sow-studio-v6')).size")
        check('1,500 prompts in the Scope step sets Large', auto == 'large', str(auto))
        await fresh.fill('[data-cover="prompts"]', '150 prompts')
        await fresh.wait_for_timeout(200)
        auto = await fresh.evaluate("JSON.parse(localStorage.getItem('partner-sow-studio-v6')).size")
        check('150 prompts sets Small', auto == 'small', str(auto))
        await fresh.click('[data-step="services"]')
        await fresh.click('#size-switch button[data-size="typical"]')
        await fresh.wait_for_timeout(150)
        await fresh.click('[data-step="scope"]')
        await fresh.fill('[data-cover="prompts"]', '3,000 prompts')
        await fresh.wait_for_timeout(200)
        manual = await fresh.evaluate("JSON.parse(localStorage.getItem('partner-sow-studio-v6')).size")
        check('a size picked by hand is kept when the prompt count changes', manual == 'typical', str(manual))
        check('no errors after exercising every template, the size switch and the rate range', not errors, '; '.join(errors)[:300])
        if SHOTS:
            os.makedirs(SHOTS, exist_ok=True)
            await page.evaluate("p=>{state.play=p;go('scope');}", 'aem')
            for step in ('scope', 'services', 'document'):
                await page.click('[data-step="' + step + '"]')
                await page.wait_for_timeout(300)
                await page.screenshot(path=os.path.join(SHOTS, f'sow_{step}.png'))
            mobile = await browser.new_page(viewport={'width': 390, 'height': 844})
            await mobile.goto('file://' + PATH)
            await mobile.wait_for_timeout(1200)
            await mobile.click('[data-step="services"]')
            await mobile.wait_for_timeout(300)
            await mobile.screenshot(path=os.path.join(SHOTS, 'sow_mobile.png'))
        await browser.close()
    print(('ALL CHECKS PASSED (%d)' % len(results)) if all(results) else ('%d OF %d CHECKS FAILED' % (results.count(False), len(results))))
    sys.exit(0 if all(results) else 1)


asyncio.run(main())
