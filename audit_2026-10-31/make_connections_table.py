"""Writes CONNECTIONS.md: each canvas connection's type, Adobe's availability and what changed in its wording,
comparing the catalog before the audit fixes (commit 310bd10) with the one built now.

    python3 sow/audit_2026-10-31/make_connections_table.py
"""
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
old = json.loads(subprocess.check_output(['git', '-C', ROOT, 'show', '310bd10:sow/canvas/catalog.json']))
new = json.load(open(os.path.join(ROOT, 'sow', 'canvas', 'catalog.json'), encoding='utf-8'))
O = {c['id']: c for c in old['connections']}
P = {p['id']: p['name'] for p in new['products']}
KIND = {'native': 'Native integration', 'platform': 'Shared-platform data path', 'extension': 'Supported extension', 'partner': 'Partner-designed workflow'}
order = ['native', 'platform', 'extension', 'partner']
rows, changed = [], 0
for c in sorted(new['connections'], key=lambda c: (order.index(c['kind']), P[c['a']] + P[c['b']])):
    o = O.get(c['id'], {})
    diffs = []
    if (o.get('gain') or {}).get('title') != (c.get('gain') or {}).get('title'):
        diffs.append(f"title: \"{(o.get('gain') or {}).get('title', '')}\" is now \"{(c.get('gain') or {}).get('title', '')}\"")
    elif (o.get('gain') or {}).get('text') != (c.get('gain') or {}).get('text'):
        diffs.append('benefit text corrected')
    if o.get('how') != c.get('how'):
        diffs.append('how it connects corrected')
    if [f['what'] for f in o.get('flows', [])] != [f['what'] for f in c.get('flows', [])]:
        diffs.append('flows corrected')
    if (o.get('source') or {}).get('url') != (c.get('source') or {}).get('url'):
        diffs.append('source replaced')
    changed += bool(diffs)
    rows.append(f"| {P[c['a']]} + {P[c['b']]} | {KIND[c['kind']]} | {c['availability']} | {len(c['prereqs'])} | {'; '.join(diffs) or 'no wording change'} |")
md = ['# Canvas connections after the audit fix', '',
      'October 31, 2026. Each of the 59 connections, typed from Adobe\'s pages and re-checked by two skeptics (`sow/canvas/research/audit_classification_2026-10-31.json`; the evidence quotes are in `sow/canvas/research/connection_types.json`). "Before it works" is the number of prerequisites shown on the card. Generated by `make_connections_table.py`.', '',
      ' | '.join([f"{KIND[k]}: {sum(1 for c in new['connections'] if c['kind'] == k)}" for k in order]) + f'. Wording corrected on {changed} of {len(rows)}.', '',
      '| Connection | Type | Availability (Adobe) | Before it works | What changed |', '|---|---|---|---|---|'] + rows
text = '\n'.join(md) + '\n'
assert '—' not in text and '–' not in text
open(os.path.join(HERE, 'CONNECTIONS.md'), 'w', encoding='utf-8').write(text)
print(f'{len(rows)} connections, {changed} with corrected wording')
